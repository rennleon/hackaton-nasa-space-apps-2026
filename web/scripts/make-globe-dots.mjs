// Writes src/lib/globeDots.ts: evenly spaced points on the sphere (Fibonacci lattice) that fall on land, for the
// faint rotating globe behind the start-page hero. Land shapes: Natural Earth 1:110m via the world-atlas package
// (public domain). Run once after changing N:  node scripts/make-globe-dots.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'

const N = 5200
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)))
const land = feature(topo, topo.objects.land)
const golden = Math.PI * (3 - Math.sqrt(5))
const out = []
for (let i = 0; i < N; i++) {
  const y = 1 - (2 * (i + 0.5)) / N
  const lat = (Math.asin(y) * 180) / Math.PI
  const lon = ((((i * golden * 180) / Math.PI) % 360) + 360) % 360 - 180
  if (lat < -60) continue // leave Antarctica out: at this size it reads as a smudge
  if (geoContains(land, [lon, lat])) out.push(Math.round(lat * 10) / 10, Math.round(lon * 10) / 10)
}
writeFileSync(
  new URL('../src/lib/globeDots.ts', import.meta.url),
  `// Generated by scripts/make-globe-dots.mjs from Natural Earth 1:110m land (public domain). Do not edit.\n` +
    `// Flat list of land points: lat, lon, lat, lon, ... in degrees.\n` +
    `export const GLOBE_DOTS: readonly number[] = [${out.join(',')}]\n`,
)
console.log(`${out.length / 2} land dots of ${N}`)
