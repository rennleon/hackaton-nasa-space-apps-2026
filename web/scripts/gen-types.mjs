// Generates src/types/contract.ts from ../contract/*.schema.json. Do not hand-edit the output.
import { compile } from 'json-schema-to-typescript'
import { readFileSync, writeFileSync } from 'node:fs'

// Pydantic puts a `title` on every property, which makes the generator emit one alias per property. Drop them.
function strip(node, root = true) {
  if (Array.isArray(node)) return node.map((n) => strip(n, false))
  if (node && typeof node === 'object') {
    const o = {}
    for (const [k, v] of Object.entries(node)) {
      if (k === 'title' && typeof v === 'string') continue
      o[k] = strip(v, false)
    }
    return o
  }
  return node
}

const opts = { bannerComment: '', additionalProperties: false, unreachableDefinitions: true }
const files = ['analysis-result', 'scan-result']
let out = '/* eslint-disable */\n// GENERATED by scripts/gen-types.mjs from ../contract/*.schema.json. Do not edit by hand.\n\n'
const seen = new Set()
for (const f of files) {
  const schema = strip(JSON.parse(readFileSync(`../contract/${f}.schema.json`, 'utf8')))
  const name = f === 'analysis-result' ? 'AnalysisResult' : 'ScanResult'
  const ts = await compile(schema, name, opts)
  // Shared definitions (Text, UnitsInfo, ...) appear in both schemas: keep the first.
  const blocks = ts.split(/\n(?=export (?:interface|type) )/)
  for (const b of blocks) {
    const m = b.match(/export (?:interface|type) (\w+)/)
    if (!m) continue
    if (seen.has(m[1])) continue
    seen.add(m[1])
    out += b.trim() + '\n\n'
  }
}
writeFileSync('src/types/contract.ts', out)
console.log('wrote src/types/contract.ts', [...seen].join(', '))
